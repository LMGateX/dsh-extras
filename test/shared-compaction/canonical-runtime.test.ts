import test from 'node:test';
import assert from 'node:assert/strict';
import { Context, symbols } from '@deepseek-ai/cordis';
import LlmRuntime, { type GenerateOptions, type StreamChunk } from '@deepseek-ai/dsh-llm';
import Storage from '@deepseek-ai/dsh-storage';
import * as Domain from '@deepseek-ai/dsh-storage-domain';
import * as Json from '@deepseek-ai/dsh-storage-json';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openSharedCompactionStore } from '../../src/shared-compaction/store.ts';
import { participateCompaction } from '../../src/shared-compaction/index.ts';
const fixed = (effort: string) => ({ enabled: true, rules: [{ scope: 'all' as const, mode: 'fixed' as const, effort }] });
test('canonical policy survives executor switch and async workspace lookup captures accepted snapshot', async (t) => {
    const ctx = new Context();
    t.after(() => ctx.fiber.dispose());
    await ctx.plugin(LlmRuntime).await();
    await ctx.plugin(Storage).await();
    await ctx.plugin(Json, { root: await mkdtemp(join(tmpdir(), 'shared-policy-')) }).await();
    await ctx.plugin(Domain, { backend: 'json' }).await();
    const store = await openSharedCompactionStore(ctx);
    await store.write({ expectedRevision: 0, defaults: fixed('canonical'), workspaceOverrides: { workspace: fixed('before') } });
    const seen: GenerateOptions[] = [];
    ctx.on('llm/stream', o => { seen.push(o); return (async function* () { yield { type: 'finish', reason: { kind: 'stop' } } as StreamChunk; })(); }, { global: true });
    let release!: (id: string) => void;
    const workspace = new Promise<string>(r => release = r);
    const one = participateCompaction(ctx, { module: 'model-policy', policy: fixed('ignored-local'), workspaceForSession: () => workspace }, () => { });
    await one.ready;
    const two = participateCompaction(ctx, { module: 'compact-context', policy: fixed('ignored-too'), workspaceForSession: () => workspace }, () => { });
    await two.ready;
    const request = { provider: 'route', model: 'model', messages: [], purpose: 'compaction', sessionId: 'session' } as unknown as GenerateOptions;
    const pending = ctx.llm.stream(request);
    await store.write({ expectedRevision: 1, defaults: fixed('canonical'), workspaceOverrides: { workspace: fixed('after') } });
    two.dispose();
    release('workspace');
    for await (const _ of pending) { }
    ;
    for await (const _ of ctx.llm.stream(request)) { }
    ;
    assert.deepEqual(seen.map(o => o.reasoningEffort), ['before', 'after']);
    await store.write({ expectedRevision: 2, defaults: { enabled: false, rules: [] }, workspaceOverrides: {} });
    assert.equal(Object.hasOwn((ctx.llm as any)[symbols.original], 'stream'), false);
    one.dispose();
});
test('inconsistent initial legacy seeds fail closed until an explicit canonical save', async (t) => {
    const ctx = new Context();
    t.after(() => ctx.fiber.dispose());
    await ctx.plugin(LlmRuntime).await();
    await ctx.plugin(Storage).await();
    await ctx.plugin(Json, { root: await mkdtemp(join(tmpdir(), 'shared-seeds-')) }).await();
    await ctx.plugin(Domain, { backend: 'json' }).await();
    let a: any, b: any;
    const model = participateCompaction(ctx, { module: 'model-policy', policy: fixed('model-seed') }, s => a = s);
    const compact = participateCompaction(ctx, { module: 'compact-context', policy: fixed('compact-seed') }, s => b = s);
    await Promise.all([model.ready, compact.ready]);
    assert.equal(a.phase, 'unavailable');
    assert.equal(b.phase, 'unavailable');
    const store = await openSharedCompactionStore(ctx);
    assert.equal(store.read().revision, 0);
    await store.write({ expectedRevision: 0, defaults: fixed('explicit'), workspaceOverrides: {} });
    assert.equal(a.phase, 'standby');
    assert.equal(b.phase, 'active');
    compact.dispose();
    model.dispose();
});
