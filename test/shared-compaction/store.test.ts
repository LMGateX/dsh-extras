import test from 'node:test';
import assert from 'node:assert/strict';
import { Context } from '@deepseek-ai/cordis';
import Storage from '@deepseek-ai/dsh-storage';
import * as Domain from '@deepseek-ai/dsh-storage-domain';
import * as Json from '@deepseek-ai/dsh-storage-json';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openSharedCompactionStore } from '../../src/shared-compaction/store.ts';
import { nativeProfileFixture } from '../native-profile-fixture.ts';
const defaults = { enabled: true, rules: [{ scope: 'all' as const, mode: 'fixed' as const, effort: 'saved' }] };
test('native profile authority serializes two entry CAS writes and preserves empty overrides', async (t) => {
    const ctx = new Context();
    t.after(() => ctx.fiber.dispose());
    (await nativeProfileFixture(t)).provide(ctx);
    await ctx.plugin(Storage).await();
    await ctx.plugin(Json, { root: await mkdtemp(join(tmpdir(), 'shared-store-')) }).await();
    await ctx.plugin(Domain, { backend: 'json' }).await();
    const a = await openSharedCompactionStore(ctx), b = await openSharedCompactionStore(ctx);
    const initial = a.read();
    assert.equal(initial.revision, 0);
    const results = await Promise.allSettled([a.write({ expectedRevision: 0, defaults, workspaceOverrides: { workspace: { enabled: true, rules: [] } } }), b.write({ expectedRevision: 0, defaults: { enabled: false, rules: [] }, workspaceOverrides: {} })]);
    assert.deepEqual(results.map(r => r.status), ['fulfilled', 'rejected']);
    assert.equal(b.read().revision, 1);
    assert.deepEqual(b.read().workspaceOverrides.workspace.rules, []);
    await assert.rejects(a.write({ expectedRevision: 1, defaults: { enabled: true, rules: [{ scope: 'all', mode: 'fixed', effort: '' }] }, workspaceOverrides: {} }), /identifier/);
    assert.equal(a.read().revision, 1);
});
test('legacy import is recoverable, preserves false/empty and never overwrites accepted canonical policy', async (t) => {
    const root = await mkdtemp(join(tmpdir(), 'shared-import-'));
    const profile = await nativeProfileFixture(t, { home: join(root, 'dsh') });
    const mount = async () => { const ctx = new Context(); profile.provide(ctx); await ctx.plugin(Storage).await(); await ctx.plugin(Json, { root }).await(); await ctx.plugin(Domain, { backend: 'json' }).await(); return { ctx, store: await openSharedCompactionStore(ctx) }; };
    const first = await mount();
    t.after(() => first.ctx.fiber.dispose());
    assert.equal(await first.store.importLegacy('compact-context', { enabled: false, rules: [] }), 'imported');
    assert.deepEqual(first.store.read().defaults, { enabled: false, rules: [] });
    assert.equal(await first.store.importLegacy('model-policy', defaults), 'conflict');
    assert.equal(first.store.read().revision, 1);
    await first.store.write({ expectedRevision: 1, defaults, workspaceOverrides: {} });
    await first.ctx.fiber.dispose();
    const second = await mount();
    t.after(() => second.ctx.fiber.dispose());
    assert.equal(second.store.read().revision, 2);
    assert.deepEqual(second.store.read().defaults, defaults);
    assert.equal(await second.store.importLegacy('compact-context', { enabled: false, rules: [] }), 'preserved');
    await assert.rejects(second.store.recoverLegacy('compact-context', 1), /revision conflict/);
    await second.store.recoverLegacy('compact-context', 2);
    assert.deepEqual(second.store.read().defaults, { enabled: false, rules: [] });
    assert.equal(second.store.read().revision, 3);
});
